/*
 * ============================================================================
 * ✒ Metadata
 *     - Title: Fixture Generator (Terrane Edition - v1.0)
 *     - File Name: make-fixture.mjs
 *     - Relative Path: tools/make-fixture.mjs
 *     - Artifact Type: CLI
 *     - Version: 1.0.0
 *     - Date: 11/09/2026
 *     - Update: Monday, November 9, 2026
 *     - Author: Dennis 'dendogg' Smaltz
 *     - A.I. Acknowledgement: Anthropic - Claude Fable 5.2
 *     - Signature: ︻デ═─── ✦ ✦ ✦ | Aim Twice, Shoot Once!
 *
 * ✒ Description:
 *     Builds a synthetic directory tree for testing Terrane at scale and
 *     for exercising write operations somewhere that does not matter. The
 *     output is test data and is labelled as such by a marker file at its
 *     root; it is never a stand-in for a real directory.
 *
 * ✒ Key Features:
 *     - Deterministic: the same seed produces the same tree
 *     - Skewed sizes (many small files, a few very large) and skewed
 *       fan-out, like real project folders
 *     - Sparse files, so a tree that reports many gigabytes uses almost no
 *       disk
 *     - Modification times spread over ten years
 *     - Deliberate edge cases: empty folders, true duplicates, same-size
 *       non-duplicates, a symbolic link, a link loop, hidden entries,
 *       an unreadable folder, and unusual names (spaces, Unicode, emoji,
 *       quotes, leading dashes, a 200-character name)
 *
 * ✒ Usage Instructions:
 *     node tools/make-fixture.mjs <target-dir> [files] [seed]
 *     The target must not exist yet; the tool refuses to write into an
 *     existing directory.
 *
 * ✒ Examples:
 *     node tools/make-fixture.mjs /tmp/terrane-small 2000
 *     node tools/make-fixture.mjs /tmp/terrane-large 250000 7
 *
 * ✒ Command-Line Arguments:
 *     Input:
 *         <target-dir>   Directory to create.
 *     Processing:
 *         [files]        Approximate file count (default 5000).
 *         [seed]         Integer seed (default 1).
 *
 * ✒ Other Important Information:
 *     - Dependencies: Node.js built-ins only
 *     - Compatible platforms: Node.js 20+; symbolic links and the
 *       unreadable folder are skipped on Windows without privileges
 * ----------------------------------------------------------------------------
 */

import fs from 'node:fs';
import path from 'node:path';

const [target, countArg = '5000', seedArg = '1'] = process.argv.slice(2);
if (!target) {
  console.error('Usage: node tools/make-fixture.mjs <target-dir> [files] [seed]');
  process.exit(1);
}
if (fs.existsSync(target)) {
  console.error(`Refusing to write into an existing path: ${target}`);
  process.exit(1);
}
const total = Number(countArg);
let seed = Number(seedArg) >>> 0;
const rnd = () => {
  seed = (seed + 0x6d2b79f5) >>> 0;
  let t = seed;
  t = Math.imul(t ^ (t >>> 15), t | 1);
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};
const pick = (a) => a[Math.floor(rnd() * a.length)];
const WORDS = 'assets archive audio build cache client core data design docs drafts export fonts icons images lib logs media models notes plates raw render scripts server shared src stems tests textures tools vendor video'.split(' ');
const EXTS = 'js ts py md json css html svg png jpg psd wav flac mp3 mp4 mov zip pdf txt csv yml blend ttf bin log'.split(' ');
const now = Date.now();

fs.mkdirSync(target, { recursive: true });
fs.writeFileSync(path.join(target, 'TERRANE_TEST_DATA.txt'), 'Synthetic test data generated by tools/make-fixture.mjs. Not a real directory.\n');

const dirs = [target];
const dirTarget = Math.max(8, Math.round(total / 14));
while (dirs.length < dirTarget) {
  const parent = rnd() < 0.3 ? dirs[dirs.length - 1 - Math.floor(rnd() * Math.min(dirs.length, 30))] : pick(dirs);
  if (parent.split(path.sep).length - target.split(path.sep).length > 11) continue;
  const dir = path.join(parent, `${pick(WORDS)}-${dirs.length.toString(36)}`);
  fs.mkdirSync(dir);
  dirs.push(dir);
}

const sparse = (file, size, mtime) => {
  const fd = fs.openSync(file, 'w');
  if (size > 0) fs.ftruncateSync(fd, size);
  fs.futimesSync(fd, mtime / 1000, mtime / 1000);
  fs.closeSync(fd);
};
for (let i = 0; i < total; i++) {
  const dir = rnd() < 0.5 ? dirs[Math.floor(rnd() ** 2.2 * dirs.length)] : pick(dirs);
  const r = rnd();
  const size = r < 0.02 ? 0 : r > 0.9995 ? Math.floor(2e9 + rnd() * 6e9) : Math.floor(Math.exp(rnd() * 13 + rnd() * 6));
  sparse(path.join(dir, `${pick(WORDS)}_${i.toString(36)}.${pick(EXTS)}`), size, now - rnd() ** 2 * 3650 * 86400000);
}

// Edge cases.
const edge = path.join(target, 'edge cases');
fs.mkdirSync(edge);
for (const n of ['empty one', 'empty two', '.hidden-folder']) fs.mkdirSync(path.join(edge, n));
fs.writeFileSync(path.join(edge, '.hidden-file'), 'hidden\n');
const body = Buffer.alloc(300000, 'terrane duplicate payload ');
for (const n of ['copy-a.dat', 'copy-b.dat', path.join('empty one', '..', 'copy-c.dat')]) fs.writeFileSync(path.join(edge, n), body);
fs.writeFileSync(path.join(edge, 'same-size-different.dat'), Buffer.alloc(300000, 'x'));
for (const n of ['name with  spaces.txt', 'ünïcødé — naïve café.md', '日本語のファイル.txt', 'emoji 🗻 file.txt', "quote's \"name\".txt".replace(/"/g, process.platform === 'win32' ? '' : '"'), '-leading-dash.txt', 'x'.repeat(200) + '.txt', 'no_extension', 'archive.tar.gz']) {
  fs.writeFileSync(path.join(edge, n), `Test file: ${n}\n`);
}
try {
  fs.symlinkSync(path.join(edge, 'copy-a.dat'), path.join(edge, 'link-to-copy-a'));
  fs.symlinkSync(edge, path.join(edge, 'link-loop'), 'dir');
} catch { /* links need privileges on Windows */ }
try {
  const sealed = path.join(edge, 'sealed');
  fs.mkdirSync(sealed);
  fs.writeFileSync(path.join(sealed, 'secret.txt'), 'x');
  fs.chmodSync(sealed, 0o000);
} catch { /* not supported */ }

console.log(`Created ${dirs.length} folders and about ${total} files in ${target}`);
